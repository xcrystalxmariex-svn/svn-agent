package com.svndev.svnagent;

import android.app.Activity;
import android.content.Intent;
import android.net.Uri;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.view.Gravity;
import android.view.View;
import android.widget.LinearLayout;
import android.widget.TextView;
import android.widget.Toast;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;

/**
 * IMPORT AGENT: picks a persona bundle (.zip/.tar.gz, PBF v1) through the
 * Storage Access Framework and deploys it into the app via PersonaImporter.
 * Each imported persona gets its own home under filesDir/agents/<id>/ and is
 * registered so the drawer launches it as a self-contained agent.
 */
public class ImportAgentActivity extends Activity {

    private static final int REQ_PICK = 9001;
    private static final String PREFS = "svnagent";
    private static final String KEY_AGENTS = "imported_agents";

    private final Handler handler = new Handler(Looper.getMainLooper());
    private TextView status;
    private TextView agents;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setPadding(dp(20), dp(30), dp(20), dp(20));
        root.setBackgroundColor(0xFF050b08);

        TextView title = new TextView(this);
        title.setText("[ SVN // IMPORT AGENT ]");
        title.setTextColor(0xFF00ff66);
        title.setTextSize(16);
        title.setTypeface(android.graphics.Typeface.MONOSPACE, android.graphics.Typeface.BOLD);
        root.addView(title, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 24));

        TextView how = new TextView(this);
        how.setText("Pick a persona bundle (.zip / .tar.gz).\n"
                + "It must contain manifest.json (PBF v1).\n"
                + "Generated by tools/export_persona.sh.");
        how.setTextColor(0xFF008844);
        how.setTextSize(11);
        how.setTypeface(android.graphics.Typeface.MONOSPACE);
        root.addView(how, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 18));

        TextView pick = button("PICK PERSONA BUNDLE", 0xFF00ff66);
        pick.setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                Intent i = new Intent(Intent.ACTION_OPEN_DOCUMENT);
                i.addCategory(Intent.CATEGORY_OPENABLE);
                i.setType("*/*");
                i.putExtra(Intent.EXTRA_MIME_TYPES, new String[]{"application/zip", "application/gzip", "application/x-gzip", "application/x-tar", "*/*"});
                startActivityForResult(i, REQ_PICK);
            }
        });
        root.addView(pick, lp(LinearLayout.LayoutParams.MATCH_PARENT, dp(52), 12));

        // ---- manually created personas (no bundle needed) ----
        TextView personaTitle = new TextView(this);
        personaTitle.setText("— OR CREATE A PERSONA PROFILE —");
        personaTitle.setTextColor(0xFF00aa44);
        personaTitle.setTextSize(11);
        personaTitle.setTypeface(android.graphics.Typeface.MONOSPACE);
        root.addView(personaTitle, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 8));

        final android.widget.EditText pName = new android.widget.EditText(this);
        pName.setSingleLine(true);
        pName.setHint("persona name");
        pName.setHintTextColor(0xFF005522);
        pName.setTextColor(0xFF00ff66);
        pName.setTypeface(android.graphics.Typeface.MONOSPACE);
        root.addView(pName, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 4));

        final android.widget.EditText pModel = new android.widget.EditText(this);
        pModel.setSingleLine(true);
        pModel.setHint("ai model (e.g. gpt-4o, gemini-2.0)");
        pModel.setHintTextColor(0xFF005522);
        pModel.setTextColor(0xFF00ff66);
        pModel.setTypeface(android.graphics.Typeface.MONOSPACE);
        root.addView(pModel, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 8));

        TextView create = button("CREATE PERSONA", 0xFF00ff66);
        create.setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                String id = PersonaManager.register(ImportAgentActivity.this,
                        pName.getText().toString(), pModel.getText().toString(), "");
                status.setText("persona registered: " + id
                        + " — memory folder auto-assigned via MEMORY backend");
                new android.os.Handler(android.os.Looper.getMainLooper())
                        .postDelayed(new Runnable() {
                            @Override public void run() { refreshAgents(); }
                        }, 600);
            }
        });
        root.addView(create, lp(LinearLayout.LayoutParams.MATCH_PARENT, dp(46), 8));

        // ---- the "packet" template: hand this to any other AI (Gemini,
        // Grok, ...) so it can produce an importable persona file ----
        TextView packet = button("GET PERSONA PACKET TEMPLATE", 0xFF00aa44);
        packet.setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                Intent send = new Intent(Intent.ACTION_SEND);
                send.setType("text/plain");
                send.putExtra(Intent.EXTRA_SUBJECT, "SVN Agent persona packet (v1)");
                send.putExtra(Intent.EXTRA_TEXT, PersonaManager.packetTemplate());
                startActivity(Intent.createChooser(send, "share persona packet"));
            }
        });
        root.addView(packet, lp(LinearLayout.LayoutParams.MATCH_PARENT, dp(46), 12));

        status = new TextView(this);
        status.setText("—");
        status.setTextColor(0xFF00aa44);
        status.setTextSize(11);
        status.setTypeface(android.graphics.Typeface.MONOSPACE);
        root.addView(status, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 18));

        agents = new TextView(this);
        agents.setTextColor(0xFF00ff66);
        agents.setTextSize(11);
        agents.setTypeface(android.graphics.Typeface.MONOSPACE);
        root.addView(agents, lp(LinearLayout.LayoutParams.MATCH_PARENT, LinearLayout.LayoutParams.WRAP_CONTENT, 18));

        refreshAgents();

        TextView removeAll = button("REMOVE ALL AGENTS", 0xFFff4444);
        removeAll.setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                getSharedPreferences(PREFS, android.content.Context.MODE_PRIVATE)
                        .edit().remove(KEY_AGENTS).apply();
                File agentsDir = new File(getFilesDir(), "agents");
                if (agentsDir.exists()) deleteRecursive(agentsDir);
                refreshAgents();
                toast("all imported agents removed");
            }
        });
        root.addView(removeAll, lp(LinearLayout.LayoutParams.MATCH_PARENT, dp(52), 36));

        TextView back = button("BACK", 0xFF008844);
        back.setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                finish();
            }
        });
        root.addView(back, lp(LinearLayout.LayoutParams.MATCH_PARENT, dp(52), 12));

        setContentView(root);
    }

    private void refreshAgents() {
        PersonaImporter imp = new PersonaImporter(this);
        String[] ids = imp.getImportedIds();
        if (ids.length == 0) {
            agents.setText("imported agents: (none)");
        } else {
            StringBuilder sb = new StringBuilder("imported agents:\n");
            for (String id : ids) {
                File home = imp.getHomeDirFor(id);
                sb.append("  - ").append(id).append("  [").append(home.getAbsolutePath()).append("]\n");
            }
            agents.setText(sb.toString());
        }
    }

    @Override
    protected void onActivityResult(int requestCode, int resultCode, Intent data) {
        super.onActivityResult(requestCode, resultCode, data);
        if (requestCode != REQ_PICK || resultCode != RESULT_OK || data == null || data.getData() == null) {
            return;
        }
        final Uri uri = data.getData();
        status.setText("deploying...");
        new Thread(new Runnable() {
            @Override
            public void run() {
                try {
                    File tmp = new File(getCacheDir(), "persona-in.bundle");
                    copyUriToFile(uri, tmp);
                    PersonaImporter imp = new PersonaImporter(ImportAgentActivity.this);
                    PersonaImporter.AgentInfo info = imp.deploy(tmp);
                    tmp.delete();
                    final String msg = "imported: " + info.name + " (" + info.id
                            + ")\nhome: " + info.home.getAbsolutePath();
                    handler.post(new Runnable() {
                        @Override
                        public void run() {
                            status.setText(msg);
                            refreshAgents();
                            toast("agent imported: " + info.name);
                        }
                    });
                } catch (final IOException e) {
                    handler.post(new Runnable() {
                        @Override
                        public void run() {
                            status.setText("IMPORT FAILED: " + e.getMessage());
                        }
                    });
                }
            }
        }).start();
    }

    private void copyUriToFile(Uri uri, File target) throws IOException {
        InputStream in = getContentResolver().openInputStream(uri);
        if (in == null) throw new IOException("cannot open picked file");
        OutputStream out = new FileOutputStream(target);
        byte[] buf = new byte[65536];
        int n;
        while ((n = in.read(buf)) != -1) out.write(buf, 0, n);
        out.close();
        in.close();
    }

    private TextView button(String text, int color) {
        TextView b = new TextView(this);
        b.setText(text);
        b.setTextColor(0xFF050b08);
        b.setTextSize(11);
        b.setTypeface(android.graphics.Typeface.MONOSPACE, android.graphics.Typeface.BOLD);
        b.setGravity(Gravity.CENTER);
        android.graphics.drawable.GradientDrawable d = new android.graphics.drawable.GradientDrawable();
        d.setColor(color);
        d.setCornerRadius(dp(4));
        b.setBackground(d);
        return b;
    }

    private void toast(String msg) {
        Toast.makeText(this, msg, Toast.LENGTH_SHORT).show();
    }

    private void deleteRecursive(File f) {
        if (f == null || !f.exists()) return;
        if (f.isDirectory()) {
            File[] kids = f.listFiles();
            if (kids != null) {
                for (File k : kids) deleteRecursive(k);
            }
        }
        f.delete();
    }

    private int dp(int v) {
        return (int) (v * getResources().getDisplayMetrics().density + 0.5f);
    }

    private LinearLayout.LayoutParams lp(int w, int h, int mb) {
        LinearLayout.LayoutParams p = new LinearLayout.LayoutParams(w, h, 0);
        p.bottomMargin = dp(mb);
        return p;
    }
}